#!/usr/bin/env node
/**
 * Writes docs/database.md from the Prisma schema and the migration SQL, so the
 * schema documentation cannot drift from the database (§22 item 2). CI
 * regenerates it and fails on a difference.
 *
 *   pnpm docs:schema
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SCHEMA = join(ROOT, 'apps/api/prisma/schema.prisma');
const MIGRATIONS = join(ROOT, 'apps/api/prisma/migrations');
const OUT = join(ROOT, 'docs/database.md');

const lines = readFileSync(SCHEMA, 'utf8').split('\n');
const models = [];
const enums = [];
let doc = [];
let current = null;

for (const raw of lines) {
  const line = raw.trim();
  if (line.startsWith('///')) {
    doc.push(line.slice(3).trim());
    continue;
  }
  const block = /^(model|enum)\s+(\w+)\s*\{$/.exec(line);
  if (block) {
    current = {
      kind: block[1],
      name: block[2],
      doc: doc.join(' '),
      fields: [],
      values: [],
      attrs: [],
    };
    (block[1] === 'model' ? models : enums).push(current);
    doc = [];
    continue;
  }
  if (!current) {
    if (!line.startsWith('//')) doc = [];
    continue;
  }
  if (line === '}') {
    current = null;
    doc = [];
    continue;
  }
  if (line === '' || line.startsWith('//')) {
    if (line === '') doc = [];
    continue;
  }
  if (current.kind === 'enum') {
    current.values.push(line.split(/\s+/)[0]);
    continue;
  }
  if (line.startsWith('@@')) {
    current.attrs.push(line);
    continue;
  }
  const m = /^(\w+)\s+([\w.]+)(\[\])?(\?)?\s*(.*)$/.exec(line);
  if (m) {
    current.fields.push({
      name: m[1],
      type: m[2],
      list: Boolean(m[3]),
      optional: Boolean(m[4]),
      attrs: m[5],
      doc: doc.join(' '),
    });
  }
  doc = [];
}

const modelNames = new Set(models.map((x) => x.name));
const tableOf = (model) => /@@map\("([^"]+)"\)/.exec(model.attrs.join(' '))?.[1] ?? model.name;
const columnOf = (field) => /@map\("([^"]+)"\)/.exec(field.attrs)?.[1] ?? field.name;
const dbType = (field) => {
  const native = /@db\.(\w+)(?:\(([^)]*)\))?/.exec(field.attrs);
  if (native) return native[2] ? `${native[1]}(${native[2]})` : native[1];
  return field.type;
};
const cell = (text) => text.replace(/\|/g, '\\|');

/** Database rules from the migrations that Prisma's schema cannot express. */
const migrationDirs = readdirSync(MIGRATIONS)
  .filter((d) => /^\d{14}_/.test(d))
  .sort();
const sql = migrationDirs
  .map((d) => readFileSync(join(MIGRATIONS, d, 'migration.sql'), 'utf8'))
  .join('\n');
const checks = new Map();
for (const m of sql.matchAll(/ALTER TABLE "(\w+)"\s+ADD CONSTRAINT "(\w+)" CHECK/g)) {
  checks.set(m[1], [...(checks.get(m[1]) ?? []), m[2]]);
}
const triggers = new Map();
for (const m of sql.matchAll(
  /CREATE (?:CONSTRAINT )?TRIGGER "?(\w+)"?[\s\S]*?\bON "?(?:public\.)?"?(\w+)"?/g,
)) {
  triggers.set(m[2], [...new Set([...(triggers.get(m[2]) ?? []), m[1]])]);
}
const partial = new Map();
for (const m of sql.matchAll(/CREATE UNIQUE INDEX "(\w+)"\s+ON\s+"(\w+)"\s*([^;]*);/g)) {
  const where = /\bWHERE\b(.*)$/s.exec(m[3])?.[1]?.trim().replace(/\s+/g, ' ');
  const expression = /^\(\s*\w+\(/.test(m[3].trim());
  if (!where && !expression) continue; // plain unique indexes are listed from the schema
  const label = where
    ? `Partial unique index \`${m[1]}\` (where ${where})`
    : `Unique index \`${m[1]}\` (expression)`;
  partial.set(m[2], [...(partial.get(m[2]) ?? []), label]);
}
const rls = new Set(
  [...sql.matchAll(/ALTER TABLE "(\w+)" ENABLE ROW LEVEL SECURITY/g)].map((m) => m[1]),
);

const out = [];
out.push(
  '# Database schema',
  '',
  '<!-- Generated by `pnpm docs:schema` from apps/api/prisma/schema.prisma and the',
  '     migration SQL. Do not edit by hand: CI regenerates this file and fails on a diff. -->',
  '',
  'Supabase Postgres, accessed only by the API through Prisma ORM 7 (`@prisma/adapter-pg`).',
  'All timestamps are `timestamptz` stored in UTC; the database session time zone is pinned',
  'to UTC and Africa/Cairo is applied only when dates are shown or entered. Primary keys',
  'are UUIDv7 unless stated otherwise.',
  '',
  'Rules Prisma cannot express — CHECK constraints, triggers (including the append-only',
  'audit log), partial unique indexes and Row Level Security — live in the migration SQL',
  'and are listed under each table. Row Level Security is enabled with **no policies** on',
  'every table, so Supabase’s public Data API (anon / authenticated keys) can read or',
  'write nothing; the API connects as the database owner. Their behaviour is covered by',
  '`apps/api/test/*database*.e2e-spec.ts`.',
  '',
  '## Migrations',
  '',
  'Applied in order by `pnpm db:deploy` (`prisma migrate deploy`, using `DIRECT_URL`):',
  '',
  ...migrationDirs.map((d) => `- \`${d}\``),
  '',
  `## Tables (${models.length})`,
  '',
  ...models.map((x) => `- [\`${tableOf(x)}\`](#${tableOf(x).replace(/_/g, '_')}) — ${x.name}`),
  '',
);

for (const model of models) {
  const table = tableOf(model);
  out.push(`### ${table}`, '');
  out.push(`Prisma model \`${model.name}\`.${model.doc ? ` ${model.doc}` : ''}`, '');
  out.push('| Column | Type | Null | Key / default | Notes |', '| --- | --- | --- | --- | --- |');
  const relations = [];
  for (const field of model.fields) {
    if (modelNames.has(field.type)) {
      const rel = /@relation\(([^)]*)\)/.exec(field.attrs)?.[1] ?? '';
      const fields = /fields:\s*\[([^\]]+)\]/.exec(rel)?.[1];
      const onDelete = /onDelete:\s*(\w+)/.exec(rel)?.[1];
      if (fields) {
        relations.push(
          `- \`${fields}\` → \`${tableOf(models.find((x) => x.name === field.type))}\`` +
            (onDelete ? ` (on delete: ${onDelete})` : ''),
        );
      }
      continue;
    }
    const keys = [];
    if (/@id\b/.test(field.attrs)) keys.push('PK');
    if (/@unique\b/.test(field.attrs)) keys.push('unique');
    const def = /@default\(((?:[^()]|\([^()]*\))*)\)/.exec(field.attrs)?.[1];
    if (def !== undefined) keys.push(`default \`${def}\``);
    if (/@updatedAt\b/.test(field.attrs)) keys.push('set on update');
    const type = enums.some((e) => e.name === field.type)
      ? `enum ${field.type}`
      : `${dbType(field)}${field.list ? '[]' : ''}`;
    out.push(
      `| \`${columnOf(field)}\` | ${type} | ${field.optional ? 'yes' : ''} | ${keys.join(', ')} | ${cell(field.doc)} |`,
    );
  }
  out.push('');
  const constraints = [];
  for (const attr of model.attrs) {
    const k = /^@@(id|unique|index)\(\[([^\]]+)\]/.exec(attr);
    if (k)
      constraints.push(
        `- ${{ id: 'Primary key', unique: 'Unique', index: 'Index' }[k[1]]}: \`${k[2]}\``,
      );
  }
  for (const label of partial.get(table) ?? []) constraints.push(`- ${label}`);
  for (const name of checks.get(table) ?? []) constraints.push(`- Check: \`${name}\``);
  for (const name of triggers.get(table) ?? []) constraints.push(`- Trigger: \`${name}\``);
  if (rls.has(table)) constraints.push('- Row Level Security enabled (no policies)');
  if (relations.length) out.push('Foreign keys:', '', ...relations, '');
  if (constraints.length) out.push('Constraints and rules:', '', ...constraints, '');
}

out.push(`## Enums (${enums.length})`, '');
out.push('| Enum | Values |', '| --- | --- |');
for (const e of enums)
  out.push(`| \`${e.name}\` | ${e.values.map((v) => `\`${v}\``).join(', ')} |`);
out.push('');

writeFileSync(OUT, out.join('\n'));
console.log(`Wrote ${OUT.slice(ROOT.length)}: ${models.length} tables, ${enums.length} enums.`);
