/**
 * The deployed FTMS web app the Android shell opens (Phase 8). One origin only:
 * the app navigates nowhere else, and only pages from it may call the native
 * plugins (see src-tauri/capabilities/remote.json).
 *
 * HTTPS is required. Plain HTTP is accepted only for local development hosts
 * (this computer, or the Android emulator's alias for it); release builds still
 * refuse cleartext traffic on Android.
 */
const DEV_HOSTS = new Set(['localhost', '127.0.0.1', '10.0.2.2']);

/** Placeholder for compile checks and tests only; never used by `android:build`. */
export const PLACEHOLDER_URL = 'https://ftms.example.invalid';

/**
 * Validates `FTMS_WEB_URL` and returns its origin.
 * @param {string | undefined} raw
 * @returns {{ ok: true, origin: string, dev: boolean } | { ok: false, error: string }}
 */
export function parseWebUrl(raw) {
  const value = (raw ?? '').trim();
  if (value === '') return { ok: false, error: 'FTMS_WEB_URL is not set.' };
  let url;
  try {
    url = new URL(value);
  } catch {
    return { ok: false, error: `FTMS_WEB_URL is not a URL: ${value}` };
  }
  if (url.username || url.password) {
    return { ok: false, error: 'FTMS_WEB_URL must not contain credentials.' };
  }
  if (url.search || url.hash || (url.pathname !== '/' && url.pathname !== '')) {
    return {
      ok: false,
      error: 'FTMS_WEB_URL must be an origin only, e.g. https://ftms.example.edu',
    };
  }
  const dev = DEV_HOSTS.has(url.hostname);
  if (url.protocol !== 'https:' && !(url.protocol === 'http:' && dev)) {
    return {
      ok: false,
      error: 'FTMS_WEB_URL must use https:// (http:// is allowed only for localhost and 10.0.2.2).',
    };
  }
  return { ok: true, origin: url.origin, dev };
}

/** The capability that lets pages of the web app (and only them) use the app's native plugins. */
export function remoteCapability(origin) {
  return {
    $schema: '../gen/schemas/mobile-schema.json',
    identifier: 'remote-web-app',
    description:
      'Generated by scripts/configure.mjs from FTMS_WEB_URL. Pages of the FTMS web app may scan QR codes, read the location when attendance needs it, and use the optional biometric login key. Nothing else.',
    remote: { urls: [`${origin}/*`] },
    windows: ['main'],
    platforms: ['android', 'iOS'],
    permissions: [
      'barcode-scanner:allow-scan',
      'barcode-scanner:allow-cancel',
      'barcode-scanner:allow-check-permissions',
      'barcode-scanner:allow-request-permissions',
      'barcode-scanner:allow-open-app-settings',
      'geolocation:allow-check-permissions',
      'geolocation:allow-request-permissions',
      'geolocation:allow-get-current-position',
      'device-key:default',
    ],
  };
}
